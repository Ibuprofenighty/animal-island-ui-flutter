"""Project reference demonstration content; no implementation is copied."""
from pathlib import Path
import re,json
root=Path(__file__).resolve().parents[1]
source=root/'scratch/reference-react/demo/components/BackTop/index.tsx'
text=source.read_text(encoding='utf-8')
rows=re.findall(r"name:\s*'([^']*)',\s*romanized:\s*'([^']*)',\s*species:\s*'([^']*)',\s*hobby:\s*'([^']*)',\s*desc:\s*'([^']*)'",text)
assert len(rows)==50,len(rows)
output="// Gallery text from pinned MIT reference demo; generated by tool/extract_residents.py.\nconst residents = <(String, String, String, String, String)>[\n"
for row in rows: output+='  ('+', '.join(json.dumps(x,ensure_ascii=False) for x in row)+'),\n'
output+='];\n'
(root/'example/lib/pages/stories/residents.dart').write_text(output,encoding='utf-8')
print('Projected 50 residents')
